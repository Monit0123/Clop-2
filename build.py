from __future__ import annotations

import argparse
import ast
import os
import py_compile
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import List, Optional, Sequence, Tuple

ROOT = Path(__file__).resolve().parent
BATCH = ROOT / "clop_batch.py"
GUI = ROOT / "clop_gui.py"
DIST = ROOT / "dist"
OUTPUT = DIST / "clop_batch_gui.py"


EXPECTED_COLLISIONS = {"main", "VERSION"}


def module_body(path: Path, drop_modules: Sequence[str]) -> Tuple[str, List[str]]:
    source = path.read_text(encoding="utf-8")
    tree = ast.parse(source, filename=str(path))
    lines = source.splitlines(keepends=True)
    drop: set = set()

    for index, node in enumerate(tree.body):
        if index == 0 and isinstance(node, ast.Expr) and isinstance(getattr(node, "value", None), ast.Constant) \
                and isinstance(node.value.value, str):
            drop.update(range(node.lineno, node.end_lineno + 1))
            continue
        if isinstance(node, ast.ImportFrom) and node.module == "__future__":
            drop.update(range(node.lineno, node.end_lineno + 1))
            continue
        if isinstance(node, ast.ImportFrom) and node.module in drop_modules:
            drop.update(range(node.lineno, node.end_lineno + 1))
            continue
        if isinstance(node, ast.Import) and any(alias.name in drop_modules for alias in node.names):
            drop.update(range(node.lineno, node.end_lineno + 1))
            continue
        if isinstance(node, ast.If) and isinstance(node.test, ast.Compare) and \
                isinstance(node.test.left, ast.Name) and node.test.left.id == "__name__":
            drop.update(range(node.lineno, node.end_lineno + 1))
            continue

    kept = [line for number, line in enumerate(lines, 1) if number not in drop]
    body = "".join(kept).strip("\n") + "\n"

    names = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names.append(node.name)
        elif isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name):
                    names.append(target.id)

    body = re.sub(r"^#!.*\n", "", body)
    body = re.sub(r"^# -\*- coding:.*\n", "", body)
    return body, names


def build() -> Path:
    for path in (BATCH, GUI):
        if not path.is_file():
            raise SystemExit(f"missing {path.name}; run this from the repository root")

    batch_body, batch_names = module_body(BATCH, drop_modules=())
    gui_body, gui_names = module_body(GUI, drop_modules=("clop_batch",))


    batch_body, renamed = re.subn(r"(?m)^def main\(", "def cli_main(", batch_body)
    if renamed != 1:
        raise SystemExit("could not rename clop_batch.main; the file changed shape")

    collisions = (set(batch_names) & set(gui_names)) - {"main"}
    unexpected = collisions - EXPECTED_COLLISIONS
    if unexpected:
        raise SystemExit(
            "these names are defined in both modules and would shadow each other: "
            f"{sorted(unexpected)}"
        )

    header = '''#!/usr/bin/env python3
"""
Clop Batch, single-file build. Generated by build.py.

    python3 clop_batch_gui.py                    browser UI on 127.0.0.1:8765
    python3 clop_batch_gui.py cli DIR [options]  command line, same options as
                                                 clop_batch.py (--help for all)
"""

from __future__ import annotations

'''

    entry = '''


def _run() -> int:
    argv = sys.argv[1:]
    if argv and argv[0] in ("cli", "batch", "--cli"):
        return cli_main(argv[1:])
    return main(argv)


if __name__ == "__main__":
    sys.exit(_run())
'''

    merged = header + batch_body + "\n\n" + gui_body + entry

    DIST.mkdir(exist_ok=True)
    OUTPUT.write_text(merged, encoding="utf-8")
    os.chmod(OUTPUT, 0o755)

    if "from clop_batch import" in merged or "import clop_batch" in merged:
        raise SystemExit("the merged file still imports clop_batch; merge failed")

    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    print(f"  {len(merged.splitlines())} lines, {len(merged.encode()) / 1024:.1f} KiB")
    if collisions:
        print(f"  names present in both modules: {sorted(collisions)} (expected: {sorted(EXPECTED_COLLISIONS)})")
    return OUTPUT


def check(path: Path) -> int:
    problems: List[str] = []

    def report(ok: bool, message: str) -> None:
        print(f"  {'ok  ' if ok else 'FAIL'} {message}")
        if not ok:
            problems.append(message)

    with tempfile.TemporaryDirectory() as tmp:
        try:
            py_compile.compile(str(path), cfile=str(Path(tmp) / "merged.pyc"), doraise=True)
            report(True, "compiles")
        except py_compile.PyCompileError as exc:
            report(False, f"compiles ({exc})")
            return 1

        result = subprocess.run([sys.executable, str(path), "--help"],
                                capture_output=True, text=True, timeout=120)
        report(result.returncode == 0 and "clop_gui" in result.stdout, "GUI mode shows --help")

        result = subprocess.run([sys.executable, str(path), "cli", "--help"],
                                capture_output=True, text=True, timeout=120)
        report(result.returncode == 0 and "batch-size" in result.stdout,
               "cli mode shows the batch options")

        target = Path(tmp) / "files"
        target.mkdir()
        (target / "a.png").write_bytes(b"x" * 100)
        result = subprocess.run(
            [sys.executable, str(path), "cli", str(target), "--allow-non-macos", "--dry-run"],
            capture_output=True, text=True, timeout=120,
        )
        report(result.returncode == 0 and "batch 1" in result.stdout,
               "cli mode plans a folder (--dry-run)")
        if problems:
            print("\n--- last output ---")
            print((result.stdout or "")[-1500:])
            print((result.stderr or "")[-1500:])
    return 1 if problems else 0


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Build the single-file Clop Batch script.")
    parser.add_argument("--check", action="store_true", help="verify the merged file after building")
    parser.add_argument("--output", metavar="PATH", help="write somewhere other than dist/clop_batch_gui.py")
    args = parser.parse_args(argv)

    global OUTPUT
    if args.output:
        OUTPUT = Path(args.output).expanduser().resolve()
        DIST.mkdir(parents=True, exist_ok=True)
    path = build()
    if args.check:
        print("checking:")
        return check(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
